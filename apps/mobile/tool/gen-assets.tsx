// Regenerates the Android app's icons and illustrations from the web app, so
// both draw exactly the same artwork. Run from the repo root:
//   node_modules/.bin/tsx apps/mobile/tool/gen-assets.tsx
// Icons: every PhosphorIcons<Weight>.<name> used in apps/mobile/lib is rendered
// from @phosphor-icons/react into lib/widgets/phosphor.dart.
// Art: VaultHero and ChainArt from apps/web/src/components/art.tsx into assets/art.
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as P from '@phosphor-icons/react/dist/ssr';
import { ChainArt, VaultHero } from '../../web/src/components/art';
(globalThis as any).React = React;

const mobile = join(__dirname, '..');
const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const used = new Set<string>();
for (const f of walk(join(mobile, 'lib')).filter((f) => f.endsWith('.dart') && !f.endsWith('phosphor.dart'))) {
  for (const m of readFileSync(f, 'utf8').matchAll(/PhosphorIcons(Duotone|Fill|Bold|Regular)\.([a-zA-Z]+)/g)) used.add(`${m[1]}.${m[2]}`);
}
const byWeight: Record<string, string[]> = {};
for (const u of [...used].sort()) { const [w, n] = u.split('.'); (byWeight[w!] ??= []).push(n!); }
let dart = `// GENERATED by apps/mobile/tool/gen-assets.tsx from @phosphor-icons/react (MIT),\n// the web app's icon set, so the Android app draws exactly the same icons.\n// Only icons the app uses. Do not edit by hand.\n\nclass PI {\n  const PI(this.svg);\n  final String svg;\n}\n\n`;
const missing: string[] = [];
for (const [w, names] of Object.entries(byWeight)) {
  dart += `abstract final class PhosphorIcons${w} {\n`;
  for (const n of names) {
    const comp = (P as any)[n[0]!.toUpperCase() + n.slice(1)];
    if (!comp) { missing.push(`${w}.${n}`); continue; }
    const svg = renderToStaticMarkup(React.createElement(comp, { weight: w.toLowerCase(), color: '#000000', size: 256 }))
      .replace(/<svg[^>]*>/, '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="#000000">').replace(/"currentColor"/g, '"#000000"');
    dart += `  static const ${n} = PI('${svg.replace(/'/g, "\'")}');\n`;
  }
  dart += `}\n\n`;
}
writeFileSync(join(mobile, 'lib/widgets/phosphor.dart'), dart);

const svgFile = (el: React.ReactElement) =>
  '<?xml version="1.0" encoding="UTF-8"?>' + renderToStaticMarkup(el).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ').replace(/[«»]/g, '');
writeFileSync(join(mobile, 'assets/art/vault_hero.svg'), svgFile(<VaultHero />));
writeFileSync(join(mobile, 'assets/art/chain_ok.svg'), svgFile(<ChainArt ok />));
writeFileSync(join(mobile, 'assets/art/chain_broken.svg'), svgFile(<ChainArt ok={false} />));
console.log(`icons: ${used.size}, missing: ${missing.join(', ') || 'none'}; art: 3 files`);
